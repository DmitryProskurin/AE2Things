package io.github.projectet.ae2things.compat.emi;

import dev.emi.emi.api.recipe.EmiRecipeCategory;
import dev.emi.emi.api.render.EmiRenderable;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;

public class EmiRecipeCategoryWithNameOverride extends EmiRecipeCategory {
    private final Component name;

    public EmiRecipeCategoryWithNameOverride(ResourceLocation id, EmiRenderable icon, Component name) {
        super(id, icon);
        this.name = name;
    }

    @Override
    public Component getName() {
        return name;
    }
}
